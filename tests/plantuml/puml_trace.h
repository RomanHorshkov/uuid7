/**
 * @file puml_trace.h
 * @brief The tracing layer of the scenario suite: each public call goes through a macro that performs it and writes the interaction as
 *        PlantUML sequence-diagram lines, one file per scenario.
 *
 * A scenario opens its diagram with PUML_BEGIN(), calls the library through PUML_GEN(), PUML_INIT(), PUML_RAISE_FLOOR(),
 * PUML_SET_RNG() and PUML_CLOCK_FAILURES(), adds PUML_NOTE(), PUML_DIVIDER() and PUML_GROUP() for what the reader should see, and
 * closes it with PUML_END(). The clock and the RNG the library calls back are the trace's own (puml_clock(), puml_rng()), so the
 * diagram shows the order in which the library uses them. Files land in $UUID7_PUML_DIR, default build/ecss/puml, relative to the
 * directory the suite runs from (the repository root under kyr-build).
 *
 * @author  Roman Horshkov <https://github.com/RomanHorshkov>
 * @date    october 2026
 */
#ifndef UUID7_PUML_TRACE_H
#define UUID7_PUML_TRACE_H

#include "uuid7.h"
#include "uuid7_test.h"

#include <errno.h>
#include <stdarg.h>
#include <stdatomic.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>

#define PUML_DIR_DEFAULT "build/ecss/puml"

/** @brief Trace state shared by the macros: the open diagram, whether callbacks trace, the scripted clock and RNG. */
typedef struct puml_trace
{
    FILE*            f;             /**< The open .puml file, NULL outside a scenario. */
    _Atomic int      quiet;         /**< Non-zero: callbacks do not trace (worker threads). */
    _Atomic uint64_t clock_ms;      /**< What puml_clock() returns. */
    _Atomic int      rng_fail;      /**< Non-zero: puml_rng() fails. */
    _Atomic uint32_t rng_counter;   /**< Next byte value puml_rng() emits. */
    _Atomic uint32_t events;        /**< Callback order counter. */
    _Atomic uint32_t last_rng_at;   /**< Event number of the last RNG call. */
    _Atomic uint32_t last_clock_at; /**< Event number of the last clock read. */
} puml_trace_t;

static puml_trace_t g_puml;

static inline void puml_vline(const char* fmt, va_list ap) __attribute__((format(printf, 1, 0)));
static inline void puml_line(const char* fmt, ...) __attribute__((format(printf, 1, 2)));

static inline void puml_vline(const char* fmt, va_list ap)
{
    if(!g_puml.f) return;
    vfprintf(g_puml.f, fmt, ap);
    fputc('\n', g_puml.f);
}

static inline void puml_line(const char* fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    puml_vline(fmt, ap);
    va_end(ap);
}

/* mkdir -p for a relative or absolute path. */
static inline int puml_mkdirs(const char* path)
{
    char   buf[512];
    size_t n = strlen(path);
    if(n == 0u || n >= sizeof(buf)) return -1;
    memcpy(buf, path, n + 1u);
    for(size_t i = 1; i <= n; ++i)
    {
        if(buf[i] == '/' || buf[i] == '\0')
        {
            const char saved = buf[i];
            buf[i]           = '\0';
            if(mkdir(buf, 0755) != 0 && errno != EEXIST) return -1;
            buf[i] = saved;
        }
    }
    return 0;
}

/** @brief Opens `<dir>/<name>.puml` and writes the header and the participants. @return 0, or -1 when the file cannot be created. */
static inline int puml_begin(const char* name, const char* title)
{
    const char* dir = getenv("UUID7_PUML_DIR");
    char        path[640];
    if(!dir || !*dir) dir = PUML_DIR_DEFAULT;
    if(puml_mkdirs(dir) != 0) return -1;
    if(snprintf(path, sizeof(path), "%s/%s.puml", dir, name) >= (int)sizeof(path)) return -1;
    g_puml.f = fopen(path, "w");
    if(!g_puml.f) return -1;
    atomic_store(&g_puml.quiet, 0);
    atomic_store(&g_puml.events, 0u);
    atomic_store(&g_puml.last_rng_at, 0u);
    atomic_store(&g_puml.last_clock_at, 0u);
    puml_line("@startuml %s", name);
    puml_line("' generated by tests/plantuml/scenarios.c (%s); do not edit", name);
    puml_line("title %s", title);
    puml_line("skinparam shadowing false");
    puml_line("skinparam sequenceMessageAlign left");
    puml_line("autonumber");
    puml_line("actor \"Caller\\n(scenario test)\" as C");
    puml_line("participant \"libuuid7\\nuuid7.h\" as L");
    puml_line("participant \"Clock\\n(test hook)\" as K");
    puml_line("participant \"RNG callback\" as R");
    return 0;
}

/** @brief Closes the diagram. */
static inline void puml_end(void)
{
    if(!g_puml.f) return;
    puml_line("@enduml");
    fclose(g_puml.f);
    g_puml.f = NULL;
}

static inline void puml_note(const char* over, const char* fmt, ...) __attribute__((format(printf, 2, 3)));

/** @brief A note over (or "left of X", "right of X") a participant; the text may hold "\n" for line breaks. */
static inline void puml_note(const char* over, const char* fmt, ...)
{
    char    text[1024];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(text, sizeof(text), fmt, ap);
    va_end(ap);
    if(strncmp(over, "left of", 7) == 0 || strncmp(over, "right of", 8) == 0)
        puml_line("note %s", over);
    else
        puml_line("note over %s", over);
    puml_line("%s", text);
    puml_line("end note");
}

/** @brief The test clock the library reads through uuid7_test_set_time_fn(): traced unless quiet. */
static inline uint64_t puml_clock(void)
{
    const uint64_t t = atomic_load(&g_puml.clock_ms);
    atomic_store(&g_puml.last_clock_at, atomic_fetch_add(&g_puml.events, 1u) + 1u);
    if(!atomic_load(&g_puml.quiet))
    {
        puml_line("L -> K : now()");
        puml_line("K --> L : %llu ms", (unsigned long long)t);
    }
    return t;
}

/** @brief The RNG callback: counting bytes 0x10, 0x11, ... (deterministic diagrams), or a failure when rng_fail is set. */
static inline int puml_rng(void* buf, size_t n)
{
    uint8_t*  out  = (uint8_t*)buf;
    const int fail = atomic_load(&g_puml.rng_fail);
    atomic_store(&g_puml.last_rng_at, atomic_fetch_add(&g_puml.events, 1u) + 1u);
    if(!fail)
    {
        for(size_t i = 0; i < n; ++i)
        {
            out[i] = (uint8_t)(atomic_fetch_add(&g_puml.rng_counter, 1u) & 0xFFu);
        }
    }
    if(!atomic_load(&g_puml.quiet))
    {
        puml_line("L -> R : fill(buf, %zu)", n);
        if(fail)
            puml_line("R --> L : -1 (no entropy)");
        else
            puml_line("R --> L : 0 [%02x %02x .. %02x]", out[0], out[1], out[n - 1u]);
    }
    return fail ? -1 : 0;
}

/** @brief Decodes the timestamp of a binary identifier. */
static inline uint64_t puml_id_ms(const uint8_t* id)
{
    uint64_t ms = 0;
    for(size_t i = 0; i < 6u; ++i)
        ms = (ms << 8) | id[i];
    return ms;
}

/** @brief Decodes the 12-bit sequence of a binary identifier. */
static inline unsigned puml_id_seq(const uint8_t* id)
{
    return ((unsigned)(id[6] & 0x0Fu) << 8) | (unsigned)id[7];
}

/** @brief The caller-side text form 8-4-4-4-12 (the library is binary-only). */
static inline void puml_id_text(const uint8_t* id, char out[37])
{
    static const char hex[] = "0123456789abcdef";
    size_t            o     = 0;
    for(size_t i = 0; i < 16u; ++i)
    {
        if(i == 4u || i == 6u || i == 8u || i == 10u) out[o++] = '-';
        out[o++] = hex[id[i] >> 4];
        out[o++] = hex[id[i] & 0x0Fu];
    }
    out[o] = '\0';
}

/** @brief uuid7_gen() traced: the call, the callbacks it makes, the return value and, on success, the decoded fields. */
static inline int puml_gen(void* out, const char* arg)
{
    puml_line("C -> L : uuid7_gen(%s)", arg);
    puml_line("activate L");
    const int rc = uuid7_gen(out);
    if(rc == 0)
    {
        char           text[37];
        const uint8_t* id = (const uint8_t*)out;
        puml_id_text(id, text);
        puml_line("L --> C : 0  %s", text);
        puml_line("note right of L : reserved (ms=%llu, seq=%u)", (unsigned long long)puml_id_ms(id), puml_id_seq(id));
    }
    else
    {
        puml_line("L --> C : %d", rc);
    }
    puml_line("deactivate L");
    return rc;
}

/** @brief uuid7_init() traced. */
static inline int puml_init(uuid7_rng_function_t fn, const char* fn_text, const void* last, const char* last_text)
{
    puml_line("C -> L : uuid7_init(%s, %s)", fn_text, last_text);
    puml_line("activate L");
    const int rc = uuid7_init(fn, last);
    puml_line("L --> C : %d", rc);
    puml_line("deactivate L");
    return rc;
}

/** @brief uuid7_raise_floor() traced; the floor's fields are shown with the call. */
static inline int puml_raise_floor(const void* last, const char* last_text)
{
    if(last)
        puml_line("C -> L : uuid7_raise_floor(%s)\\n(ms=%llu, seq=%u)", last_text, (unsigned long long)puml_id_ms((const uint8_t*)last),
                  puml_id_seq((const uint8_t*)last));
    else
        puml_line("C -> L : uuid7_raise_floor(%s)", last_text);
    puml_line("activate L");
    const int rc = uuid7_raise_floor(last);
    puml_line("L --> C : %d", rc);
    puml_line("deactivate L");
    return rc;
}

/** @brief uuid7_set_rng_func() traced. */
static inline int puml_set_rng(uuid7_rng_function_t fn, const char* fn_text)
{
    puml_line("C -> L : uuid7_set_rng_func(%s)", fn_text);
    const int rc = uuid7_set_rng_func(fn);
    puml_line("L --> C : %d", rc);
    return rc;
}

/** @brief uuid7_clock_failure_count() traced. */
static inline uint64_t puml_clock_failures(void)
{
    puml_line("C -> L : uuid7_clock_failure_count()");
    const uint64_t n = uuid7_clock_failure_count();
    puml_line("L --> C : %llu", (unsigned long long)n);
    return n;
}

#define PUML_BEGIN(name, title) puml_begin((name), (title))
#define PUML_END()              puml_end()
#define PUML_GEN(buf)           puml_gen((buf), #buf)
#define PUML_INIT(fn, last)     puml_init((fn), #fn, (last), #last)
#define PUML_RAISE_FLOOR(last)  puml_raise_floor((last), #last)
#define PUML_SET_RNG(fn)        puml_set_rng((fn), #fn)
#define PUML_CLOCK_FAILURES()   puml_clock_failures()
#define PUML_NOTE(over, ...)    puml_note((over), __VA_ARGS__)
#define PUML_DIVIDER(text)      puml_line("== %s ==", (text))
#define PUML_GROUP(kind, text)  puml_line("%s %s", (kind), (text))
#define PUML_GROUP_END()        puml_line("end")
#define PUML_SET_CLOCK(ms)      atomic_store(&g_puml.clock_ms, (uint64_t)(ms))
#define PUML_QUIET(on)          atomic_store(&g_puml.quiet, (on) ? 1 : 0)

#endif /* UUID7_PUML_TRACE_H */
